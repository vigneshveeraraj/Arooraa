package com.arooraa.leads.admin.auth.config;

import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import org.springframework.security.web.csrf.CsrfToken;
import org.springframework.web.filter.OncePerRequestFilter;

import java.io.IOException;

/**
 * CookieCsrfTokenRepository only writes the XSRF-TOKEN cookie once the deferred
 * CsrfToken is actually read; a pure REST API never reads it via a server-rendered
 * form, so this forces that read on every request, guaranteeing the cookie is present
 * for the frontend to pick up (the standard Spring Security recipe for SPA + cookie CSRF).
 */
public class CsrfCookieFilter extends OncePerRequestFilter {

    @Override
    protected void doFilterInternal(HttpServletRequest request, HttpServletResponse response, FilterChain filterChain)
            throws ServletException, IOException {
        CsrfToken csrfToken = (CsrfToken) request.getAttribute(CsrfToken.class.getName());
        if (csrfToken != null) {
            csrfToken.getToken();
        }
        filterChain.doFilter(request, response);
    }
}
